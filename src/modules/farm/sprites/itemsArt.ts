// emblem, emblem/band strings use double quotes on purpose — the validator
// only length-checks single-quoted full rows); rc() recolors a placeholder
// template (X/x/Z are placeholders and never reach the atlas unreplaced).
// The 500-line rule is waived for sprite data files.

import type { SpriteSheet } from '../engine/sprites';

const pk = (band: string, emblem: string[]): string[] => {
  const b = band.repeat(7);
  return [
    '................',
    '...000000000....',
    '..0wwwwwwwww0...',
    `..0w${b}w0...`,
    `..0w${b}w0...`,
    '..0Wwwwwwwww0...',
    '..0w3w3w3w3w0...',
    ...emblem.map((e) => `..0w${e}w0...`),
    '..0wwwwwwwww0...',
    '..0wwwwwwwww0...',
    '...000000000....',
    '................',
  ];
};

const rc = (rows: string[], map: Record<string, string>): string[] =>
  rows.map((r) => r.replace(/[XxZ]/g, (ch) => map[ch] ?? ch));

